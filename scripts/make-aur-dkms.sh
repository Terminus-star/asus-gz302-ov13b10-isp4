#!/usr/bin/env bash
# Generate the DKMS package aur/gz302-camera-dkms/: the three GZ302 camera modules (amd_isp4_capture,
# ov13b10, amd_isp4) as source, built by DKMS for every installed kernel from 6.18 on, plus the ACPI _CID
# table (acpi/gz302-camb-cid.asl) and its mkinitcpio drop-in, which let the stock kernel's amdgpu find the camera
# (findings 136-138). Tuning changes ship as a new version of this small package; no kernel is built.
#
#   ./scripts/make-aur-dkms.sh TARBALL
#   e.g. ./scripts/make-aur-dkms.sh kernel/build/tarballs/cachyos-7.2.11-1.tar.gz
#
# Raise dkms_ver below for every change (pacman, DKMS and the installer go by the version).
#
# Steps (stops at the first problem; aur/ is only written at the end):
#   1. extract the three drivers' pristine sources from TARBALL into scratch/dkms-src/run.XXXXXX/
#   2. apply the patches in $patch_dir: 0002 (amd_isp4 graph), 0004 + 0006 (ov13b10 id + GZ302 quirk), 0007
#      (capture driver, 0009-0053) and 0008 (sensor reset GPIO in amd_isp4) with -F0
#   3. lay them out flat in one folder with one Kbuild (tested: all three build from it), add dkms.conf, the ACPI
#      table (compiled here with iasl from acpi/gz302-camb-cid.asl), the mkinitcpio drop-in, the .install file and
#      PKGBUILD, then a test build against the running kernel (or KVER=)
#   4. .SRCINFO, then copy everything into aur/gz302-camera-dkms/ (files there are overwritten)
# The old amdgpu kernel patches (0001, 0003, 0005) are not used: the ACPI table and patches 0008/0053 replace them.
set -euo pipefail

project_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
tarball=${1:?usage: $0 TARBALL}
patch_dir="$project_dir/dkms/patches"	# the DKMS package's patches against the CachyOS sources
dkms_ver=0.4.1
out="$project_dir/aur/gz302-camera-dkms"
patches=(
	0002-platform-amd-isp4-add-gz302-ov13b10-graph.patch
	0004-media-ov13b10-add-i2c-device-id.patch
	0006-media-ov13b10-gz302-dmi-quirk.patch
	0007-media-amd-isp4-gz302-capture.patch
	0008-platform-amd-isp4-gz302-sensor-reset-gpio.patch
)
isp4=drivers/media/platform/amd/isp4
singles=(drivers/media/i2c/ov13b10.c drivers/platform/x86/amd/amd_isp4.c)
maintainer="Seifelden Abdelmonem <saif.elden.hatim@gmail.com>"
die() { echo "ERROR: $*" >&2; exit 1; }

# ---- 1. pristine sources ----
mkdir -p "$project_dir/scratch/dkms-src"
work=$(mktemp -d -p "$project_dir/scratch/dkms-src" run.XXXXXX)	# new each run; old ones can be removed by hand
echo "work folder: $work"
top=$(basename "$tarball" .tar.gz)	# CachyOS tarballs unpack into a folder of the same name
mkdir -p "$work/tree"
tar -xzf "$tarball" -C "$work/tree" --strip-components=1 "$top/$isp4" "${singles[@]/#/$top/}"

# ---- 2. our patches ----
for p in "${patches[@]}"; do
	patch --dry-run --batch -s -p1 -F0 -d "$work/tree" < "$patch_dir/$p" \
		|| die "$p does not apply cleanly to $top"
	patch --batch --no-backup-if-mismatch -s -p1 -F0 -d "$work/tree" < "$patch_dir/$p"
	echo "applied $p"
done

# ---- 3. package folder ----
pkg="$work/pkg"
mkdir -p "$pkg"
cp "$work/tree/$isp4"/*.[ch] "${singles[@]/#/$work/tree/}" "$pkg/"

cat > "$pkg/Kbuild" <<'EOF'
# SPDX-License-Identifier: GPL-2.0-only
# The three GZ302 camera modules from one folder (generated by scripts/make-aur-dkms.sh).
obj-m += amd_isp4_capture.o ov13b10.o amd_isp4.o
amd_isp4_capture-objs := isp4.o isp4_debug.o isp4_interface.o isp4_subdev.o isp4_video.o
EOF

# PACKAGE_VERSION is filled in by the PKGBUILD's package(), so it always equals pkgver.
cat > "$pkg/dkms.conf" <<'EOF'
# Generated by scripts/make-aur-dkms.sh in https://github.com/Terminus-star/asus-gz302-ov13b10-isp4
PACKAGE_NAME="gz302-camera"
PACKAGE_VERSION="@PKGVER@"
BUILT_MODULE_NAME[0]="amd_isp4_capture"
DEST_MODULE_LOCATION[0]="/updates/dkms"
BUILT_MODULE_NAME[1]="ov13b10"
DEST_MODULE_LOCATION[1]="/updates/dkms"
BUILT_MODULE_NAME[2]="amd_isp4"
DEST_MODULE_LOCATION[2]="/updates/dkms"
# Any kernel from 6.18 on (the oldest the sources were build-tested on, findings 143). Officially tested: CachyOS
# 7.2+ (linux-cachyos). Other kernels (CachyOS lts/rc/deckify, Arch linux/lts/zen, ...) build but are up to their
# users to test.
BUILD_EXCLUSIVE_KERNEL_MIN="6.18"
AUTOINSTALL="yes"
EOF

# ACPI _CID table (findings 136), compiled from the source in the repo so the package always matches it, and the
# drop-in that enables mkinitcpio's acpi_override hook. Installed by package() outside /usr/src (see there).
iasl -p "$pkg/gz302-camb-cid" "$project_dir/acpi/gz302-camb-cid.asl" > "$work/iasl.log" 2>&1 \
	|| die "iasl failed (see $work/iasl.log)"
grep -q "0 Errors, 0 Warnings" "$work/iasl.log" || die "iasl reported errors or warnings (see $work/iasl.log)"
cp "$project_dir/acpi/90-gz302-camera-acpi.conf" "$pkg/"

# pacman .install file (not a source file): a warning when installed on something other than a GZ302.
cat > "$pkg/gz302-camera-dkms.install" <<'EOF'
# Generated by scripts/make-aur-dkms.sh in https://github.com/Terminus-star/asus-gz302-ov13b10-isp4
post_install() {
	if ! grep -q '^GZ302' /sys/class/dmi/id/board_name 2>/dev/null; then
		echo "WARNING: this is not an ASUS ROG Flow Z13 GZ302 (board $(cat /sys/class/dmi/id/board_name 2>/dev/null))."
		echo "         gz302-camera-dkms adds an ACPI table for the GZ302 camera to every initramfs; remove the"
		echo "         package (pacman -R gz302-camera-dkms) unless you know you want it."
	fi
	echo "The ACPI camera table (/usr/lib/initcpio/acpi_override/gz302-camb-cid.aml) takes effect after a reboot."
}
post_upgrade() {
	post_install
}
EOF

mapfile -t files < <(cd "$pkg" && ls -I '*.install')	# sources, Kbuild, dkms.conf, ACPI table, drop-in; sorted
{
	cat <<EOF
# Maintainer: $maintainer
#
# Rear camera drivers for the ASUS ROG Flow Z13 2025 (GZ302EA), built by DKMS for each installed kernel from
# 6.18 on (officially tested: linux-cachyos 7.2+; other kernels are up to their users to test):
# amd_isp4_capture (ISP4 capture), ov13b10 (sensor, GZ302 quirk) and amd_isp4 (camera graph). They replace the
# kernel's own copies (DKMS installs into updates/dkms/, which is searched first).
# Sources: CachyOS $top with the asus-gz302-ov13b10-isp4 patches ${patches[*]%%-*}.
# Also installs an ACPI table that adds _CID "OMNI5C10" to the camera (\_SB.CAMB), so the stock kernel's amdgpu
# finds it, and a mkinitcpio drop-in enabling the acpi_override hook. The mkinitcpio pacman hook rebuilds every
# initramfs when this package is installed, upgraded or removed (it watches usr/lib/initcpio/*).
# Generated by scripts/make-aur-dkms.sh in https://github.com/Terminus-star/asus-gz302-ov13b10-isp4
# (edit that script, not this file).

pkgname=gz302-camera-dkms
pkgver=$dkms_ver
pkgrel=1
pkgdesc="Rear camera drivers (DKMS) and ACPI camera table for the ASUS ROG Flow Z13 GZ302"
arch=('any')
url="https://github.com/Terminus-star/asus-gz302-ov13b10-isp4"
license=('GPL-2.0-only')
# No headers package in depends (the usual rule for DKMS packages): DKMS builds for every kernel whose headers are
# installed (its pacman hook also builds for newer kernels when their headers arrive), so install the headers
# package of each kernel you boot.
depends=('dkms' 'gz302-camera-firmware')
optdepends=('linux-cachyos-headers: build the modules for linux-cachyos (the officially tested kernel)')
backup=('etc/mkinitcpio.conf.d/90-gz302-camera-acpi.conf')
install=gz302-camera-dkms.install
source=(
EOF
	for f in "${files[@]}"; do echo "    '$f'"; done
	echo ")"
	echo "b2sums=("
	for f in "${files[@]}"; do echo "    '$(b2sum "$pkg/$f" | cut -d' ' -f1)'"; done
	echo ")"
	cat <<'EOF'

package() {
	local dest="$pkgdir/usr/src/gz302-camera-$pkgver" f
	for f in "${source[@]}"; do
		case $f in
		gz302-camb-cid.aml)
			# read by mkinitcpio's acpi_override hook (its package location)
			install -Dm644 "$srcdir/$f" "$pkgdir/usr/lib/initcpio/acpi_override/$f" ;;
		90-gz302-camera-acpi.conf)
			# mkinitcpio reads drop-ins only from /etc (listed in backup=)
			install -Dm644 "$srcdir/$f" "$pkgdir/etc/mkinitcpio.conf.d/$f" ;;
		*)
			install -Dm644 "$srcdir/$f" "$dest/$f" ;;
		esac
	done
	sed -i "s/@PKGVER@/$pkgver/" "$dest/dkms.conf"
}
EOF
} > "$pkg/PKGBUILD"
bash -n "$pkg/PKGBUILD"

# Test build exactly as DKMS will run it (make -C <headers> M=<folder>), in a copy, against the newest
# the running kernel, or KVER=... (scripts/kbuild-env.sh).
source "$project_dir/scripts/kbuild-env.sh"	# KVER, KDIR, KMAKE_CC
mkdir -p "$work/build"
cp "$pkg"/*.[ch] "$pkg/Kbuild" "$work/build/"
nice -n 15 make -s -C "$KDIR" M="$work/build" "${KMAKE_CC[@]}" -j8 modules > "$work/build.log" 2>&1 \
	|| die "test build failed for $KVER (see $work/build.log)"
# kbuild's note "the compiler differs from the one used to build the kernel" (e.g. clang 23.1.3 vs 23.1.1 on stock
# CachyOS kernels) is not a code warning; DKMS sees the same. Any other warning stops the script.
grep -i "warning" "$work/build.log" | grep -v -F "the compiler differs from the one used to build the kernel" \
	&& die "test build for $KVER has warnings (see $work/build.log)"
echo "test build for $KVER: amd_isp4_capture.ko ov13b10.ko amd_isp4.ko, no warnings"

# ---- 4. .SRCINFO and copy ----
(cd "$pkg" && makepkg --printsrcinfo > .SRCINFO)
mkdir -p "$out"
cp "$pkg"/* "$pkg/.SRCINFO" "$out/"
echo "wrote $out (version $dkms_ver)"
